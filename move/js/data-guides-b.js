<h3>앱의 자동 견적은 이렇게 계산해요</h3>
<ol>
<li><b>짐 부피</b> = 짐 목록 가구·가전 크기 합 + 박스 수 × 0.07㎥</li>
<li><b>톤수</b> = 부피 ÷ 5㎥ + 여유 5% → 실제 트럭 등급으로 올림</li>
<li><b>인원</b> = 톤수에 맞춰 (5톤이면 4~5명)</li>
<li><b>본비</b> = 톤 × 8만원 + 인원 × 21만원</li>
<li><b>할증</b>은 본비에만 붙어요. 손없는날 20%, 주말 15%, 월말 10%, 월초 5%. 11/3은 월초 5%만 해당돼요. 업체에 따라 % 대신 10만~30만원을 더 받기도 해요(추정).</li>
<li><b>부대비</b> = 사다리차(층별) + 엘리베이터 사용료 + 에어컨(제조사 서비스로 표시 안 한 것만 — 우리 집 삼성 에어컨은 빠져요) + 분해조립 + 대형 냉장고 + 폐기물</li>
<li><b>기준가</b> = 본비 × (1 + 할증) + 부대비. 범위는 기준가 × 0.85 ~ × 1.25예요.</li>
